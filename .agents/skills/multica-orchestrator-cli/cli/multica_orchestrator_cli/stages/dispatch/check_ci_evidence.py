#!/usr/bin/env python3
"""Validate baseline evidence or execute one project command at an exact revision."""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path
from typing import Any

from multica_state_bundle.identities import canonical_json, digest_bytes
from multica_state_bundle.storage import atomic_bytes

CONTROL_CHECKS = (
    "orchestration-contract",
    "work-type-isolation",
    "work-item-execution-isolation",
    "cross-work-item-scope-conflict",
    "resource-lease-integrity",
    "integration-target-freshness",
    "artifact-revision-integrity",
    "permission-boundary",
    "human-approval-evidence",
)
PROJECT_CHECKS = ("project-test", "project-lint", "project-build")
ALL_CHECKS = CONTROL_CHECKS + PROJECT_CHECKS


class EvidenceError(ValueError):
    """Evidence cannot prove the requested check."""


def load(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise EvidenceError(f"cannot read JSON evidence {path}: {error}") from error
    if not isinstance(value, dict):
        raise EvidenceError("evidence must be a JSON object")
    return value


def validate_evidence(
    evidence: dict[str, Any], check: str, source: str, target: str, merge: str
) -> dict[str, Any]:
    if evidence.get("schema") != "multica-orchestrator-dispatch.integration-check-evidence.v1":
        raise EvidenceError("evidence schema is invalid")
    if evidence.get("generator") != "multica-orchestrator-dispatch.default-integration-evaluator.v1":
        raise EvidenceError("evidence was not generated by the Dispatch default evaluator")
    unsigned = dict(evidence)
    observed_digest = unsigned.pop("evidence_digest", None)
    if observed_digest != digest_bytes(canonical_json(unsigned)):
        raise EvidenceError("evidence digest is invalid")
    expected = {
        "source_revision": source,
        "target_revision": target,
        "merge_revision": merge,
    }
    if any(evidence.get(name) != value for name, value in expected.items()):
        raise EvidenceError("evidence does not match exact source, target, and merge revisions")
    checks = evidence.get("checks")
    if not isinstance(checks, dict) or not isinstance(checks.get(check), dict):
        raise EvidenceError(f"missing check evidence: {check}")
    item = checks[check]
    if item.get("state") != "PASS":
        raise EvidenceError(f"check is not PASS: {check}")
    details = item.get("details")
    if not isinstance(details, dict):
        raise EvidenceError(f"check has no typed details: {check}")
    expected_ref = f"dispatch:{check}:{digest_bytes(canonical_json(details))}"
    if item.get("evidence_ref") != expected_ref:
        raise EvidenceError(f"check evidence_ref digest is invalid: {check}")
    return {
        "check": check,
        **expected,
        "state": "PASS",
        "evidence_ref": expected_ref,
    }


def validate_project_policy(policy: dict[str, Any], check: str) -> dict[str, Any]:
    if policy.get("schema") != "multica-orchestration.ci-policy.v1":
        raise EvidenceError("project CI policy schema is invalid")
    checks = policy.get("checks")
    if not isinstance(checks, dict) or not isinstance(checks.get(check), dict):
        raise EvidenceError(f"missing project check policy: {check}")
    item = checks[check]
    command = item.get("command")
    na_policy_ref = item.get("na_policy_ref")
    if isinstance(command, str) and command.strip() and na_policy_ref is None:
        return {"check": check, "state": "COMMAND", "command": command}
    if command is None and isinstance(na_policy_ref, str) and na_policy_ref.strip() and item.get("state") == "HUMAN_APPROVED_NA":
        return {"check": check, "state": "HUMAN_APPROVED_NA", "na_policy_ref": na_policy_ref}
    raise EvidenceError(f"project check must select one command or Human-approved N/A policy: {check}")


def git_head(root: Path) -> str:
    completed = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"], text=True, capture_output=True, check=False)
    if completed.returncode:
        raise EvidenceError(completed.stderr.strip() or "cannot read repository HEAD")
    return completed.stdout.strip()


def execute_project_command(
    result: dict[str, Any],
    repository_root: Path,
    project_subpath: str,
    source: str,
    target: str,
    merge: str,
) -> dict[str, Any]:
    revisions = {
        "source_revision": source,
        "target_revision": target,
        "merge_revision": merge,
    }
    if result["state"] != "COMMAND":
        return {**result, **revisions}
    root = repository_root.expanduser().resolve()
    project = (root / project_subpath).resolve()
    try:
        project.relative_to(root)
    except ValueError as error:
        raise EvidenceError("project subpath escapes repository root") from error
    if not project.is_dir():
        raise EvidenceError("project command cwd does not exist")
    observed_head = git_head(root)
    if observed_head != merge:
        raise EvidenceError(
            f"repository HEAD {observed_head} does not match proposed merge revision {merge}"
        )
    completed = subprocess.run(
        ["bash", "-lc", result["command"]],
        cwd=project,
        text=True,
        capture_output=True,
        check=False,
    )
    receipt = {
        "schema": "multica-orchestrator-dispatch.project-command-evidence.v1",
        "check": result["check"],
        "command": result["command"],
        "cwd": str(project),
        **revisions,
        "exit_code": completed.returncode,
        "stdout_digest": digest_bytes(completed.stdout.encode("utf-8")),
        "stderr_digest": digest_bytes(completed.stderr.encode("utf-8")),
        "state": "PASS" if completed.returncode == 0 else "FAIL",
    }
    receipt["receipt_digest"] = digest_bytes(canonical_json(receipt))
    return receipt


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", choices=ALL_CHECKS, required=True)
    parser.add_argument("--evidence", type=Path)
    parser.add_argument("--source")
    parser.add_argument("--target")
    parser.add_argument("--merge")
    parser.add_argument("--project-policy", type=Path)
    parser.add_argument("--execute-project-command", action="store_true")
    parser.add_argument("--repository-root", type=Path)
    parser.add_argument("--project-subpath", default=".")
    parser.add_argument("--output", type=Path)
    arguments = parser.parse_args()
    try:
        if arguments.check in CONTROL_CHECKS:
            if (
                arguments.evidence is None
                or not arguments.source
                or not arguments.target
                or not arguments.merge
            ):
                raise EvidenceError("control checks require evidence, source, target, and merge")
            result = validate_evidence(
                load(arguments.evidence),
                arguments.check,
                arguments.source,
                arguments.target,
                arguments.merge,
            )
        else:
            if arguments.project_policy is None:
                raise EvidenceError("project checks require project-policy")
            result = validate_project_policy(load(arguments.project_policy), arguments.check)
            if arguments.execute_project_command:
                if (
                    arguments.repository_root is None
                    or not arguments.source
                    or not arguments.target
                    or not arguments.merge
                ):
                    raise EvidenceError(
                        "executed project checks require repository-root, source, target, and merge"
                    )
                result = execute_project_command(
                    result,
                    arguments.repository_root,
                    arguments.project_subpath,
                    arguments.source,
                    arguments.target,
                    arguments.merge,
                )
        encoded = json.dumps(result, ensure_ascii=False, indent=2, sort_keys=True).encode("utf-8") + b"\n"
        if arguments.output:
            atomic_bytes(arguments.output, encoded)
        print(json.dumps(result, sort_keys=True, separators=(",", ":")))
        return 0 if result.get("state") != "FAIL" else 1
    except EvidenceError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
